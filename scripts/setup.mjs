#!/usr/bin/env node
import { randomBytes } from "node:crypto";
import { constants } from "node:fs";
import { access, chmod, mkdir, open, stat, unlink } from "node:fs/promises";
import { createInterface } from "node:readline/promises";
import { stdin, stdout } from "node:process";
import { fileURLToPath } from "node:url";
import { isIP } from "node:net";
import { dirname, resolve } from "node:path";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const envPath = resolve(root, ".env");
const secretDirectory = resolve(root, "secrets");
const smtpPasswordPath = resolve(secretDirectory, "smtp_password");

const emailPattern = /^[^\s@<>]+@[^\s@<>]+\.[^\s@<>]+$/;
const hostnamePattern = /^(?=.{1,253}$)(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?)(?:\.(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?))*$/i;

export function validateSetupAnswers(a) {
  let origin;
  try { origin = new URL(a.baseUrl); } catch { throw new Error("Enter a valid public base URL."); }
  if (origin.protocol !== "https:" || origin.username || origin.password || origin.pathname !== "/" || origin.search || origin.hash)
    throw new Error("The public base URL must be an HTTPS origin, for example https://usr.example.org.");
  const adminEmail = a.adminEmail.trim().toLowerCase();
  if (!emailPattern.test(adminEmail) || adminEmail.length > 320)
    throw new Error("Enter a valid administrator email address.");
  if ((!isIP(a.smtpHost) && !hostnamePattern.test(a.smtpHost)) || a.smtpHost.length > 255)
    throw new Error("Enter an SMTP hostname without a URL scheme.");
  const smtpPort = Number(a.smtpPort);
  if (!Number.isInteger(smtpPort) || smtpPort < 1 || smtpPort > 65535)
    throw new Error("SMTP port must be between 1 and 65535.");
  if (!a.smtpUser || a.smtpUser.length > 320 || /[\r\n\u0000-\u001f]/.test(a.smtpUser))
    throw new Error("Enter an SMTP username.");
  if (typeof a.smtpPassword !== "string" || !a.smtpPassword || a.smtpPassword.length > 8192 || /[\r\n\u0000]/.test(a.smtpPassword))
    throw new Error("Enter a valid SMTP password.");
  const fromEmail = a.fromEmail.trim().toLowerCase();
  if (!emailPattern.test(fromEmail) || fromEmail.length > 320)
    throw new Error("Enter a valid sender email address.");
  if (a.fromName.length > 80 || /[\r\n\u0000-\u001f]/.test(a.fromName))
    throw new Error("Sender name is too long or contains control characters.");
  const webPort = Number(a.webPort);
  if (!Number.isInteger(webPort) || webPort < 1 || webPort > 65535)
    throw new Error("Web port must be between 1 and 65535.");
  return { ...a, baseUrl: origin.origin, adminEmail, fromEmail, smtpPort, webPort };
}

function envValue(value) {
  return `'${String(value).replaceAll("\\", "\\\\").replaceAll("'", "\\'")}'`;
}

export function renderEnvironment(a, passwordFile) {
  const dbPassword = randomBytes(32).toString("hex");
  const vars = {
    POSTGRES_PASSWORD: dbPassword,
    DATABASE_URL: `postgresql://randusr:${dbPassword}@db:5432/randusr`,
    ADMIN_BOOTSTRAP_EMAIL: a.adminEmail,
    WEB_PORT: String(a.webPort),
    API_PORT: "3001",
    API_HOST: "127.0.0.1",
    APP_BASE_URL: a.baseUrl,
    MAIL_MODE: "smtp",
    SMTP_HOST: a.smtpHost,
    SMTP_PORT: String(a.smtpPort),
    SMTP_SECURE: String(a.smtpSecure),
    SMTP_USER: a.smtpUser,
    SMTP_PASSWORD_FILE: passwordFile,
    SMTP_FROM_EMAIL: a.fromEmail,
    SMTP_FROM_NAME: a.fromName,
    VITE_SHOW_BRAND_FOOTER: "true",
    TRUST_PROXY_HOPS: "1",
    PUBLIC_REGISTRATION_ENABLED: "false",
    DEMO_MODE_ENABLED: "true",
    PRODUCT_ANALYTICS_ENABLED: "false",
  };
  return [
    "# Generated by npm run setup. File mode is 0600; keep it private and out of Git.",
    ...Object.entries(vars).map(([key, value]) => `${key}=${envValue(value)}`),
    "",
  ].join("\n");
}

async function exists(path) {
  try { await access(path, constants.F_OK); return true; } catch { return false; }
}

async function askLine(rl, label, fallback) {
  const answer = (await rl.question(`${label}${fallback ? ` [${fallback}]` : ""}: `)).trim();
  return answer || fallback;
}
async function askSecret(label) {
  if (!stdin.isTTY || typeof stdin.setRawMode !== "function")
    throw new Error("Run setup in an interactive terminal so the SMTP password is not echoed.");
  stdout.write(`${label}: `);
  stdin.setRawMode(true);
  stdin.resume();
  stdin.setEncoding("utf8");
  return new Promise((resolveSecret, rejectSecret) => {
    let value = "";
    const finish = (error) => {
      stdin.off("data", onData);
      stdin.setRawMode(false);
      stdin.pause();
      stdout.write("\n");
      error ? rejectSecret(error) : resolveSecret(value);
    };
    const onData = (data) => {
      for (const char of data) {
        if (char === "\u0003") return finish(new Error("Setup cancelled."));
        if (char === "\r" || char === "\n") return finish();
        if (char === "\u007f" || char === "\b") value = value.slice(0, -1);
        else if (char >= " " && char !== "\u007f") value += char;
      }
    };
    stdin.on("data", onData);
  });
}

async function savePrivateFile(path, contents) {
  const handle = await open(path, "wx", 0o600);
  try { await handle.writeFile(contents, "utf8"); await handle.sync(); }
  finally { await handle.close(); }
  await chmod(path, 0o600);
}

async function setup() {
  if (await exists(envPath)) throw new Error(".env already exists. Setup will not overwrite it.");
  if (await exists(smtpPasswordPath)) throw new Error("secrets/smtp_password already exists. Setup will not overwrite it.");
  stdout.write("Randomize USR self-host setup\nThis wizard writes a private .env and a separate SMTP password file.\n\n");
  const rl = createInterface({ input: stdin, output: stdout });
  try {
    const baseUrl = await askLine(rl, "Public HTTPS origin (reverse proxy domain)", "https://usr.example.org");
    const adminEmail = await askLine(rl, "Initial administrator email", "");
    const smtpHost = await askLine(rl, "SMTP hostname", "");
    const smtpPort = await askLine(rl, "SMTP port", "587");
    const smtpSecureAnswer = (await askLine(rl, "Use implicit TLS? (yes/no)", "no")).toLowerCase();
    const smtpUser = await askLine(rl, "SMTP username", "");
    const fromEmail = await askLine(rl, "Verified sender email", "");
    const fromName = await askLine(rl, "Sender display name", "Randomize USR");
    const webPort = await askLine(rl, "Loopback web port", "8080");
    rl.close();
    if (!["yes", "no"].includes(smtpSecureAnswer))
      throw new Error("Choose yes or no for SMTP implicit TLS.");
    const smtpPassword = await askSecret("SMTP password (input is hidden)");
    const answers = validateSetupAnswers({ baseUrl, adminEmail, smtpHost, smtpPort, smtpSecure: smtpSecureAnswer === "yes", smtpUser, smtpPassword, fromEmail, fromName, webPort });
    await mkdir(secretDirectory, { recursive: true, mode: 0o700 });
    const dirMode = (await stat(secretDirectory)).mode & 0o777;
    if (dirMode & 0o077) throw new Error("The secrets directory is not private; secure it with chmod 700 and retry.");
    await savePrivateFile(smtpPasswordPath, answers.smtpPassword);
    try {
      await savePrivateFile(envPath, renderEnvironment(answers, smtpPasswordPath));
    } catch (error) {
      await unlink(smtpPasswordPath).catch(() => {});
      throw error;
    }
    stdout.write("\nPrivate configuration created (.env 0600, secrets/ 0700, SMTP password 0600). No secret values were displayed.\nNext: review .env, configure your HTTPS reverse proxy, then run docker compose up --build.\n");
  } finally {
    rl.close();
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  setup().catch((error) => {
    stdout.write(`Setup failed: ${error instanceof Error ? error.message : "unknown error"}\n`);
    process.exitCode = 1;
  });
}
