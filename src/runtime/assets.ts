function sfx(
  waveform: SoundWaveformV1,
  startFrequencyHz: number,
  endFrequencyHz: number,
  durationMs: number,
  envelope: SfxRecipeV1["envelope"],
  noiseAmount = 0,
  volume = 0.8,
): SfxRecipeV1 {
  return {
    format: "randusr.sfx",
    version: 1,
    waveform,
    pulseWidth: 0.5,
    noiseAmount,
    volume,
    envelope,
    startFrequencyHz,
    endFrequencyHz,
    durationMs,
  };
}

